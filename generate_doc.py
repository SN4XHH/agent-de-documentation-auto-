# generate_doc.py
"""
Simple placeholder script for the Agent de Documentation project.
It demonstrates how you could generate documentation files automatically.
"""
import sys

def generate(name: str = "example"):
    """Generate a minimal markdown documentation file.

    Args:
        name: The name of the documentation topic.
    """
    content = f"# Documentation for {name}\n\nThis file was generated by ``generate_doc.py``.\n"
    filename = f"{name.replace(' ', '_').lower()}.md"
    with open(filename, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Generated {filename}")

if __name__ == "__main__":
    topic = sys.argv[1] if len(sys.argv) > 1 else "example"
    generate(topic)
